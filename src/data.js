export function calculateMatch(userProfile, candidate) {
  if (!userProfile) {
    return { score: candidate.match || 75, reason: 'Campus discovery match', isTwoWay: false, canTeachYou: [], wantsFromYou: [] };
  }

  const userLearns = userProfile.learns || [];
  const userTeaches = userProfile.teaches || [];
  const candTeaches = candidate.teaches || [];
  const candLearns = candidate.learns || [];

  // Direct matches
  const canTeachYou = candTeaches.filter(s => userLearns.includes(s));
  const wantsFromYou = candLearns.filter(s => userTeaches.includes(s));

  let score = 52; // baseline campus proximity score

  if (canTeachYou.length > 0) {
    score += canTeachYou.length * 24; // up to +48
  }

  if (wantsFromYou.length > 0) {
    score += wantsFromYou.length * 16; // up to +32
  }

  // Two-way synergy bonus
  const isTwoWay = canTeachYou.length > 0 && wantsFromYou.length > 0;
  if (isTwoWay) {
    score += 8;
  }

  // Same department bonus
  if (userProfile.dept && candidate.dept === userProfile.dept) {
    score += 2;
  }

  // Availability compatibility
  const userAvail = userProfile.availability || 'Both';
  const candAvail = candidate.availability || 'Both';
  if (userAvail === 'Both' || candAvail.includes(userAvail) || candAvail.includes('Both')) {
    score += 2;
  }

  const finalScore = Math.min(98, Math.max(55, Math.round(score)));

  let reason = '';
  if (isTwoWay) {
    reason = `Direct 2-way barter: ${candidate.name.split(' ')[0]} teaches ${canTeachYou[0]} & wants ${wantsFromYou[0]}`;
  } else if (canTeachYou.length > 0) {
    reason = `${candidate.name.split(' ')[0]} can mentor you in ${canTeachYou[0]}`;
  } else if (wantsFromYou.length > 0) {
    reason = `Looking for someone to teach them ${wantsFromYou[0]}`;
  } else {
    reason = 'Complementary campus learner · Same university network';
  }

  return {
    score: finalScore,
    reason,
    isTwoWay,
    canTeachYou,
    wantsFromYou
  };
}

export function getRankedPeople(userProfile, peopleList = people) {
  return peopleList
    .map(p => {
      const matchData = calculateMatch(userProfile, p);
      return {
        ...p,
        match: matchData.score,
        matchReason: matchData.reason,
        isTwoWay: matchData.isTwoWay,
        canTeachYou: matchData.canTeachYou,
        wantsFromYou: matchData.wantsFromYou
      };
    })
    .sort((a, b) => b.match - a.match);
}
